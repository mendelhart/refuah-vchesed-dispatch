/**
 * React rules are applied only when the plugins are installed.
 *
 * eslint-plugin-react and eslint-plugin-react-hooks are not currently in the
 * root devDependencies, and adding them means editing package.json, which the
 * app workstream owns. Rather than fail the lint for everyone, this resolves
 * them at config load and enables the recommended rule sets when present.
 *
 * To turn them on for good:
 *   npm i -D eslint-plugin-react eslint-plugin-react-hooks
 * and they light up on the next run with no change to this file.
 */
async function reactConfigs() {
  const load = async (name) => {
    try {
      return (await import(name)).default;
    } catch {
      return null;
    }
  };
  const react = await load('eslint-plugin-react');
  const hooks = await load('eslint-plugin-react-hooks');
  if (!react && !hooks) return [];

  return [
    {
      files: ['apps/web/**/*.{ts,tsx,js,jsx}'],
      ignores: ['apps/web/src/components/ui/**'],
      ...(react
        ? {
            plugins: { react },
            settings: { react: { version: 'detect' } },
          }
        : {}),
      rules: {
        ...(react
          ? {
              ...react.configs.recommended.rules,
              ...(react.configs['jsx-runtime']?.rules ?? {}),
              // The new JSX transform means React need not be in scope.
              'react/react-in-jsx-scope': 'off',
              'react/prop-types': 'off',
            }
          : {}),
      },
    },
    ...(hooks
      ? [
          {
            files: ['apps/web/**/*.{ts,tsx,js,jsx}'],
            ignores: ['apps/web/src/components/ui/**'],
            plugins: { 'react-hooks': hooks },
            rules: {
              // Not warnings. A missing dependency is a stale dispatcher board.
              'react-hooks/rules-of-hooks': 'error',
              'react-hooks/exhaustive-deps': 'error',
            },
          },
        ]
      : []),
  ];
}

