/**
 * Flat ESLint config for the whole monorepo.
 *
 * One config, four workspaces, three file flavours:
 *
 *   packages/shared   isomorphic TypeScript, no platform globals
 *   apps/api          Node TypeScript
 *   tools/migrate     Node TypeScript (one-shot CLI)
 *   apps/web          browser TypeScript + React, plus vendored .jsx
 *
 * Deliberately NOT type-aware (no `projectService`). Type-aware linting would
 * duplicate what `npm run typecheck` already does across four tsconfigs, and
 * would triple CI time for rules that mostly restate compiler errors. Lint
 * catches what the compiler does not; the compiler catches types.
 *
 * Run: npx eslint . --max-warnings=0
 */
